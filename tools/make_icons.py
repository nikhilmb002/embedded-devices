#!/usr/bin/env python3
"""Convert ASCII-art icons into a C header for gfx_draw_bitmap().

Source format (tools/icons/icons.txt):
    icon NAME W H
    ..##..        one line per row, '#' = on, '.' = off
    end
    derive NAME from SRC OP     (OP: flipx flipy rot90 rot180 rot270)
"""
import sys


def transform(rows, op):
    h, w = len(rows), len(rows[0])
    if op == "flipx":
        return [r[::-1] for r in rows]
    if op == "flipy":
        return rows[::-1]
    if op == "rot180":
        return [r[::-1] for r in rows[::-1]]
    if op in ("rot90", "rot270"):
        if w != h:
            raise ValueError("rot90/rot270 need a square icon")
        if op == "rot90":    # clockwise
            return ["".join(rows[h - 1 - r][c] for r in range(h)) for c in range(w)]
        return ["".join(rows[r][w - 1 - c] for r in range(h)) for c in range(w)]
    raise ValueError("unknown operation: " + op)


def pack(rows, w):
    """1 bit per pixel, rows left to right, MSB first, each row padded to a byte."""
    out = []
    for row in rows:
        for b in range((w + 7) // 8):
            v = 0
            for bit in range(8):
                col = b * 8 + bit
                if col < w and row[col] == "#":
                    v |= 0x80 >> bit
            out.append(v)
    return out


def main():
    if len(sys.argv) != 3:
        print("usage: make_icons.py icons.txt icons.h")
        return 1
    src, dst = sys.argv[1], sys.argv[2]
    icons, order, cur = {}, [], None

    def fail(n, msg):
        print(f"{src}:{n}: error: {msg}")
        sys.exit(1)

    with open(src, encoding="utf-8") as f:
        for n, raw in enumerate(f, 1):
            s = raw.strip()
            if not s or s.startswith("//"):
                continue
            p = s.split()
            if p[0] == "icon":
                if cur:
                    fail(n, "previous icon is missing 'end'")
                if len(p) != 4:
                    fail(n, "usage: icon NAME W H")
                cur = {"name": p[1], "w": int(p[2]), "h": int(p[3]), "rows": []}
            elif p[0] == "end":
                if not cur:
                    fail(n, "'end' without 'icon'")
                if len(cur["rows"]) != cur["h"]:
                    fail(n, f"icon {cur['name']}: expected {cur['h']} rows, got {len(cur['rows'])}")
                icons[cur["name"]] = cur["rows"]
                order.append(cur["name"])
                cur = None
            elif p[0] == "derive":
                if len(p) != 5 or p[2] != "from" or p[3] not in icons:
                    fail(n, "usage: derive NAME from EXISTING_ICON OP")
                try:
                    icons[p[1]] = transform(icons[p[3]], p[4])
                except ValueError as e:
                    fail(n, str(e))
                order.append(p[1])
            else:
                if not cur:
                    fail(n, "row outside an icon")
                if len(s) != cur["w"]:
                    fail(n, f"icon {cur['name']}: row has {len(s)} columns, expected {cur['w']}")
                if set(s) - set(".#"):
                    fail(n, "rows may contain only '.' and '#'")
                cur["rows"].append(s)
    if cur:
        fail(0, f"icon {cur['name']} is missing 'end'")

    with open(dst, "w", encoding="utf-8", newline="\n") as o:
        o.write("/* GENERATED by tools/make_icons.py from tools/icons/icons.txt. DO NOT EDIT. */\n")
        o.write("#ifndef EDEV_ICONS_H\n#define EDEV_ICONS_H\n\n#include <stdint.h>\n\n")
        o.write("/* Draw with: gfx_draw_bitmap(canvas, x, y, icon_NAME, ICON_NAME_W, ICON_NAME_H, true) */\n\n")
        for name in order:
            rows = icons[name]
            w, h = len(rows[0]), len(rows)
            data = pack(rows, w)
            bpr = (w + 7) // 8
            o.write(f"#define ICON_{name.upper()}_W {w}\n#define ICON_{name.upper()}_H {h}\n")
            o.write(f"static const uint8_t icon_{name}[] = {{\n")
            for r in range(h):
                chunk = data[r * bpr:(r + 1) * bpr]
                o.write("    " + ", ".join(f"0x{b:02X}" for b in chunk) + ",\n")
            o.write("};\n\n")
        o.write("#endif /* EDEV_ICONS_H */\n")
    print(f"wrote {dst}: {len(order)} icons")
    return 0


if __name__ == "__main__":
    sys.exit(main())